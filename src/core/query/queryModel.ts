/** Вид соединения после нормализации (правое сводится к левому перестановкой). */
export type JoinKind = 'inner' | 'left' | 'full';

/**
 * Один конъюнкт условия связи `ПО` (верхнеуровневый `И`-сегмент). Конструктор 1С
 * классифицирует каждый конъюнкт как СТАНДАРТНЫЙ (галочка «Произвольное» снята,
 * рендер без скобок) или ПРОИЗВОЛЬНЫЙ (галочка стоит, рендер в скобках):
 *  - СТАНДАРТНЫЙ (`custom=false`): бинарное сравнение `<seed>.<путь> <cmp>
 *    <joined>.<путь>` — оба операнда чистые точечные поля, левый принадлежит
 *    затравке цепочки, правый присоединяемой, `cmp ∈ {=,<>,<,>,<=,>=}`. Хранит
 *    `leftTableId/leftPath/operator/rightTableId/rightPath`.
 *  - ПРОИЗВОЛЬНЫЙ (`custom=true`): всё остальное (параметр/литерал/функция в
 *    операнде, перестановка операндов `joined…seed`, оба операнда одной таблицы,
 *    `ИЛИ`/`НЕ`/`ВЫБОР`, многострочное). Хранит `expression` — дословный текст.
 */
export interface JoinCondition {
  custom: boolean;
  leftTableId?: string;
  leftPath?: string;
  operator?: ConditionOperator;
  rightTableId?: string;
  rightPath?: string;
  /** Произвольный конъюнкт — полный текст выражения (без внешних скобок). */
  expression?: string;
}

export interface Join {
  /** Таблица 1 (слева в UI). */
  leftTableId: string;
  /** Таблица 2 (справа в UI). */
  rightTableId: string;
  /** «Все» у таблицы 1 — все элементы таблицы 1 сохраняются. */
  leftAll: boolean;
  /** «Все» у таблицы 2 — все элементы таблицы 2 сохраняются. */
  rightAll: boolean;
  /** «П.» — произвольное условие связи. */
  custom: boolean;
  /** Простое условие: поле таблицы 1. */
  leftPath?: string;
  /** Оператор сравнения, по умолчанию '='. */
  operator?: ConditionOperator;
  /** Простое условие: поле таблицы 2. */
  rightPath?: string;
  /**
   * Затравочная (левая по ТЕКСТУ) таблица цепочки `ИЗ`. Конструктор 1С сохраняет
   * порядок источников, введённый разработчиком; для простого условия `a = b`
   * левый/правый операнд НЕ обязаны совпадать с порядком источников (`ИЗ B
   * ВНУТРЕННЕЕ СОЕДИНЕНИЕ A ПО a.x = b.y` — затравка B, операнд слева a). Эти поля
   * задают порядок СЦЕПЛЕНИЯ независимо от leftTableId/rightTableId (которые задают
   * порядок рендера УСЛОВИЯ). Отсутствуют у соединений, созданных в UI — тогда
   * порядок цепочки берётся из leftTableId/rightTableId (фаза 6.12).
   */
  seedTableId?: string;
  /** Присоединяемая (правая по ТЕКСТУ) таблица цепочки. Парная к seedTableId. */
  joinedTableId?: string;
  /**
   * Глубина вложенности правовложенного дерева соединений (фаза 6.15.8):
   * `A СОЕД B СОЕД C ПО bc ПО ab` — подцепочка присоединяемого источника на
   * depth+1, её СОЕДИНЕНИЕ/ПО рендерятся с доп. отступом, ПО внешнего — после
   * подцепочки. Отсутствие поля = верхняя цепочка (depth 0). Список joins —
   * преордер дерева: вложенные соединения идут сразу за своим внешним.
   */
  depth?: number;
  /** Произвольное условие — полный текст выражения. */
  expression?: string;
  /**
   * Разработчик во ВВОДЕ обернул всё условие `ПО` в одну сбалансированную внешнюю
   * пару скобок (`ПО (a = b)`). Конструктор 1С сохраняет это решение, поэтому флаг
   * управляет внешними скобками одиночного условия при рендере (фаза 6.12). НЕ
   * относится к составным условиям с верхнеуровневым И/ИЛИ (там скобки вокруг
   * подконъюнктов, а не вокруг всего выражения).
   */
  parenthesized?: boolean;
  /**
   * Опциональное соединение построителя отчётов (фаза 6.15.13): всё соединение
   * целиком обёрнуто в фигурные скобки в исходнике
   * (`{<вид> СОЕДИНЕНИЕ <источник> ПО <условие>}`). Конструктор 1С сохраняет это
   * как ДИНАМИЧЕСКОЕ соединение построителя: рендерится `{` перед видом соединения
   * и `}` после условия `ПО`. Обычное соединение печатается без скобок.
   */
  optional?: boolean;
  /**
   * Последнее опциональное соединение в своём блоке `{…}`. Один блок построителя
   * может объединять НЕСКОЛЬКО соединений подряд (`{J1 ПО … J2 ПО …}`): `{`
   * печатается перед первым опциональным соединением блока, `}` — после условия
   * `ПО` соединения, помеченного этим флагом (фаза 6.16). Если флаг не задан у
   * опционального соединения, за ним в том же блоке следует ещё одно.
   */
  optionalLast?: boolean;
  /**
   * Поконъюнктное условие `ПО`, разбитое по верхнеуровневым `И` (фаза 6.13).
   * Каждый конъюнкт несёт собственный флаг `custom`: стандартный рендерится без
   * скобок, произвольный — в скобках (`ПО c0\n\t\tИ (c1)`). Когда задано,
   * генератор рендерит условие из этого списка; верхнеуровневые поля
   * `leftPath/operator/rightPath/custom/expression/parenthesized` — зеркало
   * `conditions[0]` для обратной совместимости UI. Отсутствует у соединений из
   * UI с одиночным условием (тогда генератор откатывается к верхнеуровневым полям).
   */
  conditions?: JoinCondition[];
}

