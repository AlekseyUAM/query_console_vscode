import type { MetaTable } from '../metadata/types';

/**
 * Резолвер метаданных для развёртки `*` (фаза 6.15.15).
 *
 * Конструктор 1С разворачивает `ВЫБРАТЬ *` / `Таблица.* КАК ПолеN` в полный список
 * колонок таблицы по метаданным. Парсер/генератор — pure-TS без доступа к ФС,
 * поэтому состав колонок поставляется снаружи через этот интерфейс. Источник —
 * `loadMetadataFromYaml(tmp/parser_data/cf)` в слое приёмки (`oracleAccept`) и
 * метаданные конфигурации в webview/extension.
 *
 * Контракт: вернуть описатель таблицы по её полному имени (`Справочник.X`,
 * `РегистрСведений.Y` и т. п.) или `undefined`, если таблица неизвестна. Для
 * неизвестной таблицы (а также источника-параметра `&Имя` и временной `#Имя`)
 * звезда НЕ разворачивается — поведение остаётся прежним (см. expandStarFields).
 */
export interface MetadataResolver {
  tableByFullName(fullName: string): MetaTable | undefined;
}
