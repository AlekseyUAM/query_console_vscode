import type { MetaTable } from '../metadata/types';

/**
 * Резолвер метаданных для развёртки `*` (фаза 6.15.15).
 *
 * Конструктор 1С разворачивает `ВЫБРАТЬ *` / `Таблица.* КАК ПолеN` в полный список
 * колонок таблицы по метаданным. Парсер/генератор — pure-TS без доступа к ФС,
 * поэтому состав колонок поставляется снаружи через этот интерфейс. Источник —
 * `loadMetadataFromYaml(tmp/parser_data/cf)` в слое приёмки (`oracleAccept`) и
 * метаданные конфигурации в webview/extension.
 *
 * Контракт: вернуть описатель таблицы по её полному имени (`Справочник.X`,
 * `РегистрСведений.Y` и т. п.) или `undefined`, если таблица неизвестна. Для
 * неизвестной таблицы (а также источника-параметра `&Имя` и временной `#Имя`)
 * звезда НЕ разворачивается — поведение остаётся прежним (см. expandStarFields).
 */
export interface MetadataResolver {
  tableByFullName(fullName: string): MetaTable | undefined;
  /**
   * Каноническое полное имя метаданных для источника, найденного без учёта
   * регистра (`Справочник.x` → `Справочник.X`), включая табличные части
   * (3-сегментное имя). `undefined`, если таблица неизвестна. Конструктор 1С
   * печатает имя метаданных в каноническом написании, а псевдоним источника
   * (выбранный пользователем) сохраняет как есть — поэтому канонизируется только
   * сторона ИМЕНИ. Необязателен для обратной совместимости резолверов.
   */
  canonicalFullName?(fullName: string): string | undefined;
  /**
   * Описатель ВИРТУАЛЬНОЙ таблицы (срез РС / Остатки-Обороты РН/РБ) по полному
   * имени-срезу (`РегистрСведений.X.СрезПоследних`). Нужен развёртке `ВЫБРАТЬ *`
   * по источнику-срезу: состав колонок берётся из виртуальной MetaTable (тот же
   * порядок, что у конструктора 1С). `tableByFullName` намеренно НЕ возвращает
   * виртуальные таблицы (приоритет реальной), поэтому слой выделен отдельно.
   * Необязателен для обратной совместимости резолверов.
   */
  virtualTableByFullName?(fullName: string): MetaTable | undefined;
}
