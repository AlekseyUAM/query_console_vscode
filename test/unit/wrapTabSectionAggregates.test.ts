import { describe, it, expect } from 'vitest';
import { parseBatch } from '../../src/core/query/sdblParser';
import { generateBatch } from '../../src/core/query/sdblGenerator';
import type { MetadataResolver } from '../../src/core/query/metadataResolver';
import type { MetaTable } from '../../src/core/metadata/types';

// Инлайн-метаданные. Геометрия проекции и нумерация Поле{n} подтверждены живым
// оракулом (mcp validate_query на Справочник.Пользователи.КонтактнаяИнформация и
// Справочник.ШаблоныСообщений.Параметры).
const ТАБ: MetaTable = {
  kind: 'Справочник', name: 'Таб', fullName: 'Справочник.Таб',
  fields: [
    { name: 'Ссылка', kind: 'standard', types: [] },
    { name: 'Реквизит1', kind: 'attribute', types: [] },
  ],
  tabularSections: [
    {
      kind: 'ТабличнаяЧасть', name: 'Строки', fullName: 'Справочник.Таб.Строки',
      fields: [
        { name: 'Колонка', kind: 'attribute', types: [] },
        { name: 'Колонка2', kind: 'attribute', types: [] },
      ],
    },
  ],
};

const resolver: MetadataResolver = {
  tableByFullName: (fullName) => (fullName === 'Справочник.Таб' ? ТАБ : undefined),
};

const render = (input: string, r?: MetadataResolver): string =>
  generateBatch(parseBatch(input, r));

describe('wrapTabSectionAggregates — обёртка агрегата над колонкой ТЧ в проекцию', () => {
  it('ВЫБОР с КОЛИЧЕСТВО над колонкой ТЧ → проекция ТЧ с внутренним псевдонимом Поле1', () => {
    const out = render([
      'ВЫБРАТЬ',
      '\tТ.Ссылка,',
      '\tВЫБОР КОГДА КОЛИЧЕСТВО(Т.Строки.Колонка) > 0 ТОГДА ИСТИНА ИНАЧЕ ЛОЖЬ КОНЕЦ КАК ЕстьСтроки',
      'ИЗ Справочник.Таб КАК Т',
    ].join('\n'), resolver);
    expect(out).toBe([
      'ВЫБРАТЬ',
      '\tТ.Ссылка КАК Ссылка,',
      '\tТ.Строки.(',
      '\t\tВЫБОР',
      '\t\t\tКОГДА КОЛИЧЕСТВО(Т.Строки.Колонка) > 0',
      '\t\t\t\tТОГДА ИСТИНА',
      '\t\t\tИНАЧЕ ЛОЖЬ',
      '\t\tКОНЕЦ КАК Поле1',
      '\t) КАК ЕстьСтроки',
      'ИЗ',
      '\tСправочник.Таб КАК Т',
    ].join('\n'));
  });

  it('два поля-агрегата над ОДНОЙ ТЧ сливаются в одну проекцию (Поле1, Поле2; псевдоним = первого)', () => {
    const out = render([
      'ВЫБРАТЬ',
      '\tТ.Ссылка,',
      '\tВЫБОР КОГДА КОЛИЧЕСТВО(Т.Строки.Колонка) > 0 ТОГДА ИСТИНА ИНАЧЕ ЛОЖЬ КОНЕЦ КАК ЕстьА,',
      '\tВЫБОР КОГДА КОЛИЧЕСТВО(Т.Строки.Колонка2) > 1 ТОГДА 1 ИНАЧЕ 0 КОНЕЦ КАК ЕстьБ',
      'ИЗ Справочник.Таб КАК Т',
    ].join('\n'), resolver);
    expect(out).toBe([
      'ВЫБРАТЬ',
      '\tТ.Ссылка КАК Ссылка,',
      '\tТ.Строки.(',
      '\t\tВЫБОР',
      '\t\t\tКОГДА КОЛИЧЕСТВО(Т.Строки.Колонка) > 0',
      '\t\t\t\tТОГДА ИСТИНА',
      '\t\t\tИНАЧЕ ЛОЖЬ',
      '\t\tКОНЕЦ КАК Поле1,',
      '\t\tВЫБОР',
      '\t\t\tКОГДА КОЛИЧЕСТВО(Т.Строки.Колонка2) > 1',
      '\t\t\t\tТОГДА 1',
      '\t\t\tИНАЧЕ 0',
      '\t\tКОНЕЦ КАК Поле2',
      '\t) КАК ЕстьА',
      'ИЗ',
      '\tСправочник.Таб КАК Т',
    ].join('\n'));
  });

  it('без резолвера — поле остаётся обычным ВЫБОР (поведение прежнее)', () => {
    const out = render([
      'ВЫБРАТЬ',
      '\tВЫБОР КОГДА КОЛИЧЕСТВО(Т.Строки.Колонка) > 0 ТОГДА ИСТИНА ИНАЧЕ ЛОЖЬ КОНЕЦ КАК ЕстьСтроки',
      'ИЗ Справочник.Таб КАК Т',
    ].join('\n'));
    expect(out).toBe([
      'ВЫБРАТЬ',
      '\tВЫБОР',
      '\t\tКОГДА КОЛИЧЕСТВО(Т.Строки.Колонка) > 0',
      '\t\t\tТОГДА ИСТИНА',
      '\t\tИНАЧЕ ЛОЖЬ',
      '\tКОНЕЦ КАК ЕстьСтроки',
      'ИЗ',
      '\tСправочник.Таб КАК Т',
    ].join('\n'));
  });

  it('агрегат над колонкой НЕ-ТЧ (обычный реквизит) не заворачивается', () => {
    const out = render([
      'ВЫБРАТЬ',
      '\tВЫБОР КОГДА КОЛИЧЕСТВО(Т.Реквизит1) > 0 ТОГДА ИСТИНА ИНАЧЕ ЛОЖЬ КОНЕЦ КАК Поле',
      'ИЗ Справочник.Таб КАК Т',
    ].join('\n'), resolver);
    expect(out).toContain('\tВЫБОР');
    expect(out).not.toContain('.Строки.(');
    expect(out).not.toContain('Реквизит1.(');
  });
});
