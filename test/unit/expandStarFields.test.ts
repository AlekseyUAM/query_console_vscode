import { describe, it, expect } from 'vitest';
import { parseBatch } from '../../src/core/query/sdblParser';
import { generateBatch } from '../../src/core/query/sdblGenerator';
import type { MetadataResolver } from '../../src/core/query/metadataResolver';
import type { MetaTable } from '../../src/core/metadata/types';

// Инлайн-метаданные (мини-схема) — фиксируем в тесте, чтобы не зависеть от
// НЕтрекаемого tmp/parser_data. Состав/порядок проверены на живом оракуле
// (mcp validate_query) — см. комментарии у конкретных кейсов.
const ТАБ: MetaTable = {
  kind: 'Справочник', name: 'Таб', fullName: 'Справочник.Таб',
  fields: [
    { name: 'Ссылка', kind: 'standard', types: [] },
    { name: 'ПометкаУдаления', kind: 'standard', types: [] },
    { name: 'Предопределенный', kind: 'standard', types: [] },
    { name: 'ИмяПредопределенныхДанных', kind: 'standard', types: [] },
    { name: 'Наименование', kind: 'standard', types: [] },
    { name: 'Реквизит1', kind: 'attribute', types: [] },
  ],
  tabularSections: [
    {
      kind: 'ТабличнаяЧасть', name: 'Состав', fullName: 'Справочник.Таб.Состав',
      fields: [
        { name: 'Ссылка', kind: 'standard', types: [] },
        { name: 'НомерСтроки', kind: 'standard', types: [] },
        { name: 'Товар', kind: 'attribute', types: [] },
      ],
    },
  ],
};

const resolver: MetadataResolver = {
  tableByFullName: (fullName) => (fullName === 'Справочник.Таб' ? ТАБ : undefined),
};

const render = (input: string, r?: MetadataResolver): string =>
  generateBatch(parseBatch(input, r));

describe('expandStarFields — развёртка * по метаданным', () => {
  it('ВЫБРАТЬ * по единственному источнику: порядок полей, ТЧ, завершающие стандартные', () => {
    // Порядок: Ссылка, ПометкаУдаления, Наименование, Реквизит1 → ТЧ Состав →
    // завершающие Предопределенный/ИмяПредопределенныхДанных (как у конструктора).
    const out = render('ВЫБРАТЬ * ИЗ Справочник.Таб КАК Таб', resolver);
    expect(out).toBe([
      'ВЫБРАТЬ',
      '\tТаб.Ссылка КАК Ссылка,',
      '\tТаб.ПометкаУдаления КАК ПометкаУдаления,',
      '\tТаб.Наименование КАК Наименование,',
      '\tТаб.Реквизит1 КАК Реквизит1,',
      '\tТаб.Состав.(',
      '\t\tСсылка КАК Ссылка,',
      '\t\tНомерСтроки КАК НомерСтроки,',
      '\t\tТовар КАК Товар',
      '\t) КАК Состав,',
      '\tТаб.Предопределенный КАК Предопределенный,',
      '\tТаб.ИмяПредопределенныхДанных КАК ИмяПредопределенныхДанных',
      'ИЗ',
      '\tСправочник.Таб КАК Таб',
    ].join('\n'));
  });

  it('Таблица.* с префиксом-псевдонимом разворачивается так же', () => {
    const a = render('ВЫБРАТЬ Таб.* ИЗ Справочник.Таб КАК Таб', resolver);
    const b = render('ВЫБРАТЬ * ИЗ Справочник.Таб КАК Таб', resolver);
    expect(a).toBe(b);
  });

  it('дедуп псевдонима: явное поле занимает имя, развёрнутая колонка получает суффикс', () => {
    // Подтверждено оракулом: Таб.* + Реквизит1 КАК Наименование → у звёздного
    // Наименование псевдоним Наименование1, явное поле сохраняет Наименование и
    // выводится ПОСЛЕ завершающих полей.
    const out = render(
      'ВЫБРАТЬ Таб.*, Таб.Реквизит1 КАК Наименование ИЗ Справочник.Таб КАК Таб',
      resolver
    );
    expect(out).toContain('\tТаб.Наименование КАК Наименование1,');
    // явное поле — после завершающих стандартных
    const iTrailing = out.indexOf('ИмяПредопределенныхДанных');
    const iExplicit = out.indexOf('Таб.Реквизит1 КАК Наименование');
    expect(iExplicit).toBeGreaterThan(iTrailing);
    // ровно одно «Наименование» без суффикса (явное), одно с суффиксом (звёздное)
    expect(out.match(/КАК Наименование,/g) ?? []).toHaveLength(0); // только перед ИЗ нет запятой
    expect(out).toContain('Таб.Реквизит1 КАК Наименование\nИЗ');
  });

  it('источник-параметр (&Имя): звезда удаляется, прочие поля сохраняются', () => {
    const out = render(
      'ВЫБРАТЬ *, NULL КАК Активность ИЗ &ИмяТаблицы КАК Об',
      resolver
    );
    expect(out).toBe('ВЫБРАТЬ\n\tNULL КАК Активность\nИЗ\n\t&ИмяТаблицы КАК Об');
  });

  it('источник-параметр и звезда — единственное поле: весь запрос пуст', () => {
    expect(render('ВЫБРАТЬ * ИЗ &ИмяТаблицы КАК Об', resolver)).toBe('');
  });

  it('временная таблица (#Имя): звезда удаляется → пустой запрос', () => {
    expect(render('ВЫБРАТЬ * ИЗ #Таблица', resolver)).toBe('');
  });

  it('таблица без метаданных: звезда удаляется (не падает)', () => {
    expect(render('ВЫБРАТЬ * ИЗ Справочник.Неизвестная КАК Н', resolver)).toBe('');
  });

  it('без резолвера поведение прежнее: звезда остаётся * КАК Поле1', () => {
    expect(render('ВЫБРАТЬ * ИЗ Справочник.Таб КАК Таб')).toBe(
      'ВЫБРАТЬ\n\t* КАК Поле1\nИЗ\n\tСправочник.Таб КАК Таб'
    );
  });

  it('звезда среди явных полей: разворачивается на своей позиции', () => {
    // Поля перед звездой остаются в начале, звёздные колонки — следом.
    const out = render(
      'ВЫБРАТЬ Таб.Реквизит1 КАК Р, Таб.* ИЗ Справочник.Таб КАК Таб',
      resolver
    );
    expect(out.startsWith('ВЫБРАТЬ\n\tТаб.Реквизит1 КАК Р,\n\tТаб.Ссылка КАК Ссылка,')).toBe(true);
  });
});
