import { describe, it, expect } from 'vitest';
import { parseBatch } from '../../src/core/query/sdblParser';
import { generateBatch } from '../../src/core/query/sdblGenerator';
import type { MetadataResolver } from '../../src/core/query/metadataResolver';
import type { MetaTable } from '../../src/core/metadata/types';

// Инлайн-метаданные. Поле Автор ссылается на Справочник.Пользователи — навигация
// к идентификационным реквизитам ИБ через него конструктор молча отбрасывает
// (подтверждено mcp validate_query на Справочник.ВариантыОтчетов.Автор).
const ВАРИАНТЫ: MetaTable = {
  kind: 'Справочник', name: 'ВариантыОтчетов', fullName: 'Справочник.ВариантыОтчетов',
  fields: [
    { name: 'Ссылка', kind: 'standard', types: [] },
    { name: 'Отчет', kind: 'attribute', types: [{ ref: { kind: 'Справочник', name: 'Отчеты' } }] },
    { name: 'Автор', kind: 'attribute', types: [{ ref: { kind: 'Справочник', name: 'Пользователи' } }] },
  ],
};

const resolver: MetadataResolver = {
  tableByFullName: (f) => (f === 'Справочник.ВариантыОтчетов' ? ВАРИАНТЫ : undefined),
};

const render = (input: string, r?: MetadataResolver): string =>
  generateBatch(parseBatch(input, r));

describe('dropUserIBConditions — тихий дроп навигации к реквизитам ИБ пользователя', () => {
  it('конъюнкт Автор.ИдентификаторПользователяИБ отбрасывается, прочие сохраняются', () => {
    const out = render([
      'ВЫБРАТЬ',
      '\tВарианты.Ссылка КАК Ссылка',
      'ИЗ',
      '\tСправочник.ВариантыОтчетов КАК Варианты',
      'ГДЕ',
      '\tВарианты.Автор = &Автор',
      '\tИ Варианты.Автор.ИдентификаторПользователяИБ = &GUID',
      '\tИ НЕ Варианты.ПометкаУдаления',
    ].join('\n'), resolver);
    expect(out).toBe([
      'ВЫБРАТЬ',
      '\tВарианты.Ссылка КАК Ссылка',
      'ИЗ',
      '\tСправочник.ВариантыОтчетов КАК Варианты',
      'ГДЕ',
      '\tВарианты.Автор = &Автор',
      '\tИ НЕ Варианты.ПометкаУдаления',
    ].join('\n'));
  });

  it('навигация к обычному реквизиту (Автор.Наименование) сохраняется', () => {
    const out = render([
      'ВЫБРАТЬ',
      '\tВарианты.Ссылка КАК Ссылка',
      'ИЗ',
      '\tСправочник.ВариантыОтчетов КАК Варианты',
      'ГДЕ',
      '\tВарианты.Автор.Наименование = &Н',
    ].join('\n'), resolver);
    expect(out).toContain('Варианты.Автор.Наименование = &Н');
  });

  it('навигация через поле НЕ-пользователя (Отчет.…) не трогается', () => {
    const out = render([
      'ВЫБРАТЬ',
      '\tВарианты.Ссылка КАК Ссылка',
      'ИЗ',
      '\tСправочник.ВариантыОтчетов КАК Варианты',
      'ГДЕ',
      '\tВарианты.Отчет.ИдентификаторПользователяИБ = &GUID',
    ].join('\n'), resolver);
    expect(out).toContain('Варианты.Отчет.ИдентификаторПользователяИБ = &GUID');
  });

  it('без резолвера конъюнкт сохраняется (поведение прежнее)', () => {
    const out = render([
      'ВЫБРАТЬ',
      '\tВарианты.Ссылка КАК Ссылка',
      'ИЗ',
      '\tСправочник.ВариантыОтчетов КАК Варианты',
      'ГДЕ',
      '\tВарианты.Автор.ИдентификаторПользователяИБ = &GUID',
    ].join('\n'));
    expect(out).toContain('Варианты.Автор.ИдентификаторПользователяИБ = &GUID');
  });
});
